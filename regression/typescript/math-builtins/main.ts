// ES2024 sec-math.abs, sec-math.floor, sec-math.ceil, sec-math.sqrt
console.assert(Math.abs(-5) === 5);
console.assert(Math.abs(3) === 3);
console.assert(Math.floor(3.7) === 3);
console.assert(Math.ceil(3.2) === 4);
console.assert(Math.sqrt(9) === 3);
console.assert(Math.max(1, 5, 3) === 5);
console.assert(Math.min(1, 5, 3) === 1);
