#!/usr/bin/env python3
"""Slice the driver's cleanup loop body out of the source, verbatim.

harness_cleanup_step.c proves its invariant over the loop body of
ena_tx_cleanup rather than by calling it, which is what removes the ring-size
bound.  Until now that body was RETYPED into the harness, so the ring 8, 16
and 32 results rested on a hand transcription matching
ena_ethdev.c:3229-3253.

This replaces the retyping with a slice.  The emitted header is the driver's
own lines, dedented and otherwise untouched: no statement is rewritten, no
branch is dropped, and the generator makes no editorial choice at all, which
is the point.  The fast-free branch comes along too, dead under offloads == 0
but present, so enabling it later is a harness change rather than a
re-transcription.

The harness binds the driver's names to its own state around the include, so
the slice compiles unmodified.

  gen_cleanup_body.py            write cleanup_body_generated.h
  gen_cleanup_body.py --check    fail if the file is stale

Run check_citations.py as well: this guarantees the slice matches the source
it was taken from, and that guarantees the line range still means what the
harness says it does.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = "/tmp/dpdk/drivers/net/ena/ena_ethdev.c"
LO, HI = 3229, 3253
DEST = os.path.join(HERE, "cleanup_body_generated.h")


def build():
    if not os.path.isfile(SRC):
        print(f"gen_cleanup_body: no driver source at {SRC}", file=sys.stderr)
        return None
    with open(SRC, errors="replace") as fh:
        lines = fh.read().splitlines()
    if HI > len(lines):
        print(f"gen_cleanup_body: {SRC} has {len(lines)} lines, needs {HI}",
              file=sys.stderr)
        return None
    region = lines[LO - 1:HI]

    # Dedent by the smallest indentation present, so the block sits at one
    # level inside the harness.  Tabs are expanded first so the arithmetic is
    # not confused by mixed indentation.
    expanded = [ln.replace("\t", "        ") for ln in region]
    indents = [len(ln) - len(ln.lstrip()) for ln in expanded if ln.strip()]
    cut = min(indents) if indents else 0
    body = [(ln[cut:] if ln.strip() else "") for ln in expanded]

    out = [
        "/* GENERATED by gen_cleanup_body.py -- do not edit.",
        " *",
        f" * {os.path.basename(SRC)} lines {LO}-{HI}, verbatim apart from",
        " * dedentation: the body of ena_tx_cleanup's loop.  It is sliced rather",
        " * than retyped so that harness_cleanup_step.c proves its invariant over",
        " * the driver's own statements, and the ring 8/16/32 results no longer",
        " * rest on a hand transcription.",
        " *",
        " * The harness declares the names this block uses -- tx_ring, req_id,",
        " * tx_info, mbuf, next_to_clean, total_tx_descs, total_tx_pkts,",
        " * fast_free, pkts_to_clean, pkt_cnt, mbuf_cnt -- immediately before",
        " * including it, and reads them back immediately after.",
        " */",
        "",
    ]
    out.extend(body)
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    text = build()
    if text is None:
        return 1
    if args.check:
        if not os.path.exists(DEST):
            print(f"{DEST} is missing; run gen_cleanup_body.py",
                  file=sys.stderr)
            return 1
        current = open(DEST).read()
        if current != text:
            print(f"{DEST} is STALE: the driver's loop body has changed.",
                  file=sys.stderr)
            print("Regenerate it and re-run the cleanup step proofs; the "
                  "invariant may no longer hold for the new body.",
                  file=sys.stderr)
            return 1
        print(f"{os.path.basename(DEST)} matches {os.path.basename(SRC)}"
              f":{LO}-{HI}")
        return 0
    with open(DEST, "w") as fh:
        fh.write(text)
    print(f"wrote {DEST} from {SRC}:{LO}-{HI}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
