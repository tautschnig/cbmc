static std::string lower(std::string s)
{
  for(char &c : s)
    c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
  return s;
}

java_locale_symbolst java_any_locale_symbols()
{
  return {
    {},
    {java_case_familyt::ROOT,
     java_case_familyt::TURKIC,
     java_case_familyt::LITHUANIAN}};
}

java_locale_symbolst java_locale_symbols(const std::string &tag)
{
  static const std::map<std::string, std::string> table = []()
  {
    std::map<std::string, std::string> result;
    for(const auto &entry : locale_numbers)
      result.emplace(lower(entry.first), entry.second);
    return result;
  }();
  // tags are case-insensitive, and "_" is the separator of Locale.toString
  std::string key = lower(tag);
  std::replace(key.begin(), key.end(), '_', '-');
  const std::string language = key.substr(0, key.find('-'));
  java_locale_symbolst result;
  if(language == "tr" || language == "az")
    result.cases = {java_case_familyt::TURKIC};
  else if(language == "lt")
    result.cases = {java_case_familyt::LITHUANIAN};
  else
    result.cases = {java_case_familyt::ROOT};
  // An extension (as -u-nu-thai) may select other digits, and a private use
  // subtag (-x-) other data.
  if(
    key.find("-u-") != std::string::npos ||
    key.find("-x-") != std::string::npos)
  {
    return result;
  }
  // the tag, or the tags it falls back to (without its last subtags)
  for(std::string t = key;;)
  {
    const auto found = table.find(t);
    if(found != table.end())
    {
      std::vector<std::pair<unsigned, unsigned>> pairs;
      std::istringstream in{found->second};
      std::string pair;
      while(in >> pair)
      {
        const std::size_t slash = pair.find('/');
        pairs.emplace_back(
          std::strtoul(pair.substr(0, slash).c_str(), nullptr, 16),
          std::strtoul(pair.substr(slash + 1).c_str(), nullptr, 16));
      }
      result.numbers = pairs;
      return result;
    }
    const std::size_t dash = t.rfind('-');
    if(dash == std::string::npos)
      return result;
    t = t.substr(0, dash);
  }
}

java_locale_symbolst java_default_locale_symbols()
{
  if(config.java.locale.empty())
    return java_any_locale_symbols();
  return java_locale_symbols(config.java.locale);
}
